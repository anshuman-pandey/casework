"""Validate translation catalogs and bundle them without runtime dependencies."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
LANGUAGES = ("en", "de", "es", "ja", "zh-Hans", "zh-Hant")


def build(check=False):
    catalogs = {
        code: json.loads((ROOT / "locales" / f"{code}.json").read_text())
        for code in LANGUAGES
    }
    english = catalogs["en"]
    for code, messages in catalogs.items():
        if messages.keys() != english.keys():
            raise ValueError(f"{code}: missing or extra translation keys")
        for key, value in messages.items():
            if not isinstance(value, str) or not value.strip():
                raise ValueError(f"{code}: empty translation for {key}")
            if sorted(re.findall(r"\{\w+\}", key)) != sorted(re.findall(r"\{\w+\}", value)):
                raise ValueError(f"{code}: placeholder mismatch for {key}")
    output = "// Generated by scripts/build_locales.py; edit locales/*.json instead.\n"
    output += "window.CASEWORK_MESSAGES = " + json.dumps(catalogs, ensure_ascii=False, separators=(",", ":")) + ";\n"
    target = ROOT / "casework/web/locales.js"
    if check:
        if target.read_text() != output:
            raise ValueError("Translation bundle is stale. Run python3 scripts/build_locales.py")
    else:
        target.write_text(output)
    print(f"Validated {len(english)} messages in {len(catalogs)} languages")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    build(parser.parse_args().check)
